/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_LPUART1_UART_Init();
  MX_TIM2_Init();
  /* USER CODE BEGIN 2 */
  // 啟動 UART 接收中斷
  HAL_UART_Receive_IT(&hlpuart1, &rx_data, 1);

  // 啟動 TIM2 的 PWM 通道 (PA5 綠燈, PB3 紅燈)
  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_2);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
    while (1)
    {
    	uint32_t current_time = HAL_GetTick();

    	    // --- 核心邏輯升級：警報優先權最高 ---
    	    // 如果紅燈警報被觸發，強制沒收綠燈的解鎖狀態！
    	    if (system_alarm == 1) {
    	        unlock_state = 0;
    	    }

    	    // --- 功能 1：綠燈解鎖呼吸燈 ---
    	    if (unlock_state == 1) {
    	        if (current_time - green_last_tick >= 15) {
    	            green_last_tick = current_time;
    	            green_pwm += green_step;

    	            if (green_pwm >= 1000) {
    	                green_pwm = 1000;
    	                green_step = -5;
    	            } else if (green_pwm <= 0 && green_step < 0) {
    	                green_pwm = 0;
    	                green_step = 5;
    	                unlock_state = 0;
    	            }
    	            __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, green_pwm);
    	        }
    	    } else {
    	        // 只要 unlock_state 變成 0，綠燈就會立刻被這行強制熄滅並重置
    	        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, 0);
    	        green_pwm = 0;
    	        green_step = 5;
    	    }

    	    // --- 功能 2：紅燈防拆警報閃爍 ---
    	    if (system_alarm == 1) {
    	        if (current_time - red_last_tick >= 100) {
    	            red_last_tick = current_time;
    	            red_state = !red_state;

    	            if (red_state == 1) {
    	                __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, 500);
    	            } else {
    	                __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, 0);
    	            }
    	        }
    	    } else {
    	        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, 0);
    	        red_state = 0;
        }
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    }
  /* USER CODE END 3 */
}

