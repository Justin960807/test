void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
    if (huart->Instance == LPUART1) {
        // 1. 將收到的字元存入陣列，並隨時封裝成完整字串
        rx_buffer[rx_index] = rx_data;
        rx_index++;
        rx_buffer[rx_index] = '\0'; // 補上結尾讓 strstr 可以讀取

        // 2. 暴力搜尋：不管有沒有換行符號，只要字串內出現 "PASS=103" 就解鎖
        if (strstr(rx_buffer, "PASS=103") != NULL) {
            unlock_state = 1;         // 密碼命中，觸發綠燈呼吸
            rx_index = 0;             // 歸零陣列索引
            memset(rx_buffer, 0, 20); // 清空陣列
        }

        // 3. 防止陣列溢位：如果輸入太長都沒中，自動歸零重新接收
        if (rx_index >= 19) {
            rx_index = 0;
            memset(rx_buffer, 0, 20);
        }

        // 重新啟動接收
        HAL_UART_Receive_IT(&hlpuart1, &rx_data, 1);
    }
}

